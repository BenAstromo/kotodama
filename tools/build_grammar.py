"""Build grammar_jlpt.json from OpenJLPT's grammar lists.

Run from the working folder that holds ojlpt/grammar/n1..5.json
(https://github.com/evanclan/OpenJLPT, data/json/grammar/, CC BY-SA 4.0):

    python -I -X utf8 tools/build_grammar.py <addon_dir>

Output: a JSON list, N5 → N1 in OpenJLPT's order, each point
{id, level, pattern, romaji, meaning, formation, ex_ja, ex_en, notes}
(the first example sentence only, to keep the file small).
"""
import json
import os
import sys

addon = sys.argv[1]
out = []
for n in (5, 4, 3, 2, 1):
    for g in json.load(open(f"ojlpt/grammar/n{n}.json", encoding="utf-8")):
        assert g["level"] == f"N{n}", g
        ex = (g.get("examples") or [{}])[0]
        out.append({
            "id": g["id"], "level": g["level"], "pattern": g["pattern"],
            "romaji": g.get("romaji", ""), "meaning": g.get("meaning", ""),
            "formation": g.get("formation", ""),
            "ex_ja": ex.get("ja", ""), "ex_en": ex.get("en", ""),
            "notes": g.get("notes", ""),
        })
path = os.path.join(addon, "grammar_jlpt.json")
with open(path, "w", encoding="utf-8", newline="\n") as f:
    json.dump({"_source": "OpenJLPT grammar points (CC BY-SA 4.0), "
                          "generated by tools/build_grammar.py; don't edit by hand.",
               "points": out}, f, ensure_ascii=False, separators=(",", ":"))
print(len(out), "grammar points →", path, os.path.getsize(path), "bytes")
