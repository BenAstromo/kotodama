"""Build kana_ok.txt (2026-10-14): list words (JLPT lists + frequency list)
whose kana spelling may match in sentences although they're listed with
kanji. The parser's script rule (kana text only matches words listed in
kana, so はし never becomes 橋) broke on everyday words listed in kanji:
先生になった read as に+な+っ+た, ものです as も+のです (found by the MeCab
comparison, tools/accuracy/mecab_compare.py).

A word qualifies when JMdict marks its first sense "usually written using
kana alone" (成る, 物, 事, 様, 無い …), plus HAND below (common in kana but
not flagged: 言う, 取る, 訳 …). 橋 / 箸 aren't flagged, so はし stays blocked.

    cd %TEMP% && python -I -X utf8 <addon>/tools/build_kana_ok.py <addon>
(needs data/jmdict.pkl in the current folder, like build_jlpt.py)
"""
import os, pickle, re, sys

sys.stdout.reconfigure(encoding="utf-8")
A = sys.argv[1]
J = pickle.load(open("data/jmdict.pkl", "rb"))
UK = "word usually written using kana alone"
HAND = {("言う", "いう"), ("取る", "とる"), ("訳", "わけ"), ("時", "とき"), ("中", "なか"),
        ("方", "ほう"), ("滅多", "めった"), ("本当", "ほんとう"), ("本当", "ほんと"), ("良い", "いい"),
        ("良い", "よい"), ("下さい", "ください"), ("頂く", "いただく"), ("致す", "いたす"),
        ("出来る", "できる"), ("色々", "いろいろ"), ("沢山", "たくさん"), ("大丈夫", "だいじょうぶ"),
        ("今日", "きょう"), ("一緒", "いっしょ"), ("事", "こと"), ("物", "もの"), ("所", "ところ"),
        ("行く", "いく"), ("上げる", "あげる"), ("欲しい", "ほしい"), ("過ぎる", "すぎる"),
        ("全く", "まったく"), ("一人", "ひとり"), ("二人", "ふたり"), ("事", "ごと"),
        ("癖", "くせ"), ("一体", "いったい"), ("私", "わたし"),
        ("早い", "はやい"), ("早く", "はやく"), ("始める", "はじめる"), ("始まる", "はじまる"),
        ("初めて", "はじめて")}
KANJI = re.compile(r"[㐀-鿿]")


def hira(s):
    return "".join(chr(ord(c) - 0x60) if 0x30A1 <= ord(c) <= 0x30F6 else c for c in s)


uk = set()
for e in J.values():
    if e["misc"] and UK in (e["misc"][0] or []):   # first sense; "any sense" let 浜 はま in
        for k in e["keb"]:
            for r in e["reb"]:
                uk.add((k, hira(r)))

words = set()
for lvl in ("n5", "n4", "n3", "n2", "n1"):
    for line in open(os.path.join(A, f"jlpt_{lvl}.txt"), encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        p = line.rstrip("\n").split("\t")
        if len(p) >= 2:
            words.add((p[0], p[1]))
for line in open(os.path.join(A, "freq_bccwj.txt"), encoding="utf-8"):
    if line.startswith("#") or not line.strip():
        continue
    p = line.rstrip("\n").split("\t")
    if len(p) >= 2:
        words.add((p[0], p[1]))

out = sorted((d, r) for d, r in words
             if KANJI.search(d) and ((d, hira(r)) in uk or (d, hira(r)) in HAND))
with open(os.path.join(A, "kana_ok.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("# Words listed with kanji whose kana spelling may match in sentences (JMdict 'usually\n")
    f.write("# kana' + a hand list). Generated by tools/build_kana_ok.py; JMdict (EDRDG), CC BY-SA 4.0.\n")
    for d, r in out:
        f.write(f"{d}\t{r}\n")
print(len(out), "words")
