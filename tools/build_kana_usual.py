"""Dev tool (2026-10-16): build kana_usual.txt, list words written with kanji
that real text usually writes in kana (あきらめる, ふもと, とがめる), so
the parser may match their kana spelling. kana_ok.txt covers the words
JMdict flags "usually kana"; this one measures usage instead: MeCab
(fugashi + unidic-lite, dev only, never shipped) reads every Tatoeba
sentence, and a word qualifies when at least MIN_SHARE of its uses (and at
least MIN_USES of them) are spelled in hiragana only. Short readings stay
out (MIN_READING kana): two-kana spellings (すむ, かく) are the likeliest to
be pieces of other words or particles.

    python -I -X utf8 tools/build_kana_usual.py <jpn_sentences.tsv> [pylib folder]

(pylib folder: where fugashi is installed; default %LOCALAPPDATA%/jlpt_devtools/pylib)
"""
import collections, os, sys

sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, sys.argv[2] if len(sys.argv) > 2 else
                os.path.join(os.environ["LOCALAPPDATA"], "jlpt_devtools", "pylib"))
from fugashi import Tagger  # noqa: E402

TOOLS = os.path.dirname(os.path.abspath(__file__))
A = os.path.dirname(TOOLS)
exec(open(os.path.join(TOOLS, "gemini_grammar_review", "verdicts", "gem_head.py"), encoding="utf-8").read())
sp = __import__("jlpt_progress.sentence_parser", fromlist=["x"])

MIN_USES = 5
MIN_SHARE = 0.5
MIN_READING = 3
# MeCab's lemma was another word, or the kana spelling is a grammar piece
# (checked by hand, 2026-10-16)
EXCLUDE = {"出でる",      # おいでよ / 〜ないで
           "仕様",        # どうしよう (する volitional)
           "孵る",        # かえる is 帰る / 変える
           "澄ます",      # すます is 済ます
           "浸かる",      # 見つかる → み + つかる
           "撓",          # しおり is 栞
           "諮る",        # はかる is 図る / 計る
           "仕舞い", "仕舞",   # 〜てしまい
           "辺り",        # 〜にあたり (当たる)
           "如何",        # いかん (行かん, いけない)
           "敵う", "適う"}   # stem かない: しかない, おかない, 行かない
CONTENT = {"動詞", "形容詞", "副詞", "名詞", "形状詞", "連体詞", "接続詞", "感動詞"}


def hira(s):
    return "".join(chr(ord(c) - 0x60) if 0x30A1 <= ord(c) <= 0x30F6 else c for c in s)


def is_hira(s):
    return bool(s) and all(0x3041 <= ord(c) <= 0x309F or c == "ー" for c in s)


# our kanji words by spelling: 諦める → [(諦める, あきらめる)]
words = collections.defaultdict(set)
for f, entries in sp.lexicon().items():
    if sp._has_kanji(f):
        for _p, d, r in entries:
            if sp._has_kanji(d):
                words[f].add((d, r))
kana_ok = {tuple(line.rstrip("\n").split("\t")[:2])     # kana_ok.txt only, not this tool's own output
           for line in open(os.path.join(A, "kana_ok.txt"), encoding="utf-8")
           if line.strip() and not line.startswith("#")}

tagger = Tagger()
kana = collections.Counter()
kanji = collections.Counter()
examples = collections.defaultdict(list)
with open(sys.argv[1], encoding="utf-8") as f:
    for n, line in enumerate(f):
        parts = line.rstrip("\n").split("\t")
        if len(parts) < 3:
            continue
        t = sp.clean(parts[2])
        for w in tagger(t):
            ft = w.feature
            if ft.pos1 not in CONTENT or not ft.lemma or not ft.lForm:
                continue
            lemma = ft.lemma.split("-")[0]
            key = (lemma, hira(ft.lForm))
            if is_hira(w.surface):
                kana[key] += 1
                if len(examples[key]) < 2:
                    examples[key].append(t)
            elif sp._has_kanji(w.surface):
                kanji[key] += 1

out = []
for (lemma, reading), k in kana.items():
    total = k + kanji[(lemma, reading)]
    if k < MIN_USES or k / total < MIN_SHARE or len(reading) < MIN_READING:
        continue
    for d, r in words.get(lemma, ()):
        if sp._hira(r) == reading and (d, r) not in kana_ok and d not in EXCLUDE:
            out.append((d, r, k, total, examples[(lemma, reading)]))
out.sort(key=lambda x: -x[2])
with open(os.path.join(A, "kana_usual.txt"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("# List words written with kanji that Tatoeba usually writes in kana (MeCab count:\n")
    fh.write("# kana uses / all uses). Generated by tools/build_kana_usual.py (dev only).\n")
    for d, r, k, total, _ex in sorted(out, key=lambda x: (x[1], x[0])):
        fh.write(f"{d}\t{r}\t{k}/{total}\n")
print(len(out), "words")
for d, r, k, total, ex in out:
    print(f"  {d}\t{r}\t{k}/{total}\t{ex[0][:40] if ex else ''}")
