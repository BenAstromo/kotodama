"""Build kanji_jlpt.txt from OpenJLPT's kanji lists.

Run from the working folder that holds ojlpt/kanji/n1..5.json
(https://github.com/evanclan/OpenJLPT, data/json/kanji/, CC BY-SA 4.0):

    python -I -X utf8 tools/build_kanji.py <addon_dir>

Format: char TAB level TAB freq TAB strokes TAB meanings (; ) TAB on (、) TAB
kun (、) TAB flags. Lines are ordered N5 → N1, most common first inside a
level (KANJIDIC2 newspaper frequency; kanji without one last).
Flag "supp": OpenJLPT's "supplementary" kanji, not on Waller's kanji list but
needed by that level's vocabulary (分 at N5 for 分かる).
"""
import json
import os
import sys

addon = sys.argv[1]
LEVELS = ["N5", "N4", "N3", "N2", "N1"]
rows = []
for lvl in LEVELS:
    items = json.load(open(f"ojlpt/kanji/n{lvl[1]}.json", encoding="utf-8"))
    items.sort(key=lambda k: (k["freq"] is None, k["freq"] or 0, k["character"]))
    for k in items:
        assert k["level"] == lvl, k
        rows.append("\t".join([
            k["character"], lvl, str(k["freq"] or ""), str(k["strokes"] or ""),
            "; ".join(k["meanings"]),
            "、".join(k["onyomi"]),
            "、".join(k["kunyomi"]),
            "supp" if k.get("supplementary") else "",
        ]))

out = os.path.join(addon, "kanji_jlpt.txt")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("# JLPT kanji by level, from OpenJLPT (CC BY-SA 4.0): Jonathan Waller's\n"
            "# levels (CC BY) + KANJIDIC2 readings/meanings/frequency (EDRDG, CC BY-SA 4.0).\n"
            "# Generated by tools/build_kanji.py; don't edit by hand.\n")
    f.write("\n".join(rows) + "\n")
print(len(rows), "kanji →", out)
