"""Dev tool (2026-10-14): build kinds_fix.txt, conjugation classes for list
words the parser can't conjugate because their meanings.json entry has no
usable part of speech (なる maps to the suffix なる "that is in", so なった
was never read as なる). Uses MeCab (fugashi + unidic-lite, installed outside
the add-on); only the small result file ships.

    python -I -X utf8 tools/build_kinds_fix.py
"""
import os, sys

sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.path.join(os.environ["LOCALAPPDATA"], "jlpt_devtools", "pylib"))
from fugashi import Tagger  # noqa: E402

TOOLS = os.path.dirname(os.path.abspath(__file__))
A = os.path.dirname(TOOLS)
exec(open(os.path.join(TOOLS, "gemini_grammar_review", "verdicts", "gem_head.py"), encoding="utf-8").read())
sp = __import__("jlpt_progress.sentence_parser", fromlist=["x"])
tagger = Tagger()
sp._KINDS_FIX = {}     # judge words without the current table (else they look fixed already)
sp._KIND_CACHE.clear()


def hira(s):
    return "".join(chr(ord(c) - 0x60) if 0x30A1 <= ord(c) <= 0x30F6 else c for c in s)


ENDINGS = tuple("うくぐすつぬぶむる")
out = [("ない", "ない", "adj-i", "無い"),    # listed in kana; its meanings entry has no POS
       ("しかる", "しかる", "v5", "叱る")]     # kana しかる is 然る in meanings and MeCab (recall test 5)
seen = {("ない", "ない"), ("しかる", "しかる")}
for entries in sp.lexicon().values():
    for _prio, d, r in entries:
        if (d, r) in seen:
            continue
        seen.add((d, r))
        if sp.kinds_of(d, r) or not (d.endswith(ENDINGS) or d.endswith("い")):
            continue
        toks = list(tagger(d))
        if len(toks) != 1:
            continue
        f = toks[0].feature
        if not (f.cForm or "").startswith("終止形") or d in ("ない", "いい"):
            continue                      # a noun-like stem (伺い) or a grammar ending
        kana = hira(f.kana or "")
        if kana and kana != hira(r):
            continue                      # MeCab read it as another word
        kind = None
        if f.pos1 == "動詞":
            ct = f.cType or ""
            if ct.startswith("五段"):
                kind = "v5"
            elif ct.startswith(("上一段", "下一段")):
                kind = "v1"
            elif ct.startswith("カ行変格"):
                kind = "vk"
        elif f.pos1 == "形容詞" and d.endswith("い"):
            kind = "adj-i"
        if kind:
            out.append((d, r, kind, f.lemma))
with open(os.path.join(A, "kinds_fix.txt"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("# Conjugation classes for list words whose meanings.json entry has no usable part of\n")
    fh.write("# speech (なる → v5). Generated by tools/build_kinds_fix.py with MeCab/UniDic (dev only).\n")
    for d, r, k, lemma in sorted(out):
        fh.write(f"{d}\t{r}\t{k}\t{lemma}\n")
print(len(out), "words")
for row in sorted(out)[:40]:
    print(" ", *row)
